#define PHY_CTL_SIDDQ            BIT3

#define PMU_AHB_ICHR8_EN         BIT10
#define PMU_AHB_INCR4_BURST_EN   BIT9
#define PMU_AHB_INCRX_ALIGN_EN   BIT8
